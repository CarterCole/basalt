"""Byte-exact index reproduction against the stored corpus, PROTOCOL §13 / §14.2.

This is the test an implementation must pass to claim L2. It is what makes
"two independent implementations agree" a mechanical fact rather than a matter
of opinion: the fixtures in ``conformance/vaults/minimal/expected/`` were
generated by the TypeScript reference implementation, and this module rebuilds
them from content alone with a completely separate codebase.
"""

from __future__ import annotations

import json

import pytest

from basalt.canonical import canonical_json, comparable
from basalt.indexer import EPOCH
from basalt.transport.local import LocalTransport
from basalt.vault import INDEX_KINDS, Vault

from .conftest import CONFORMANCE

ROOT = CONFORMANCE / "vaults" / "minimal"


@pytest.fixture(scope="module")
def rebuilt() -> dict[str, dict]:
    vault = Vault(LocalTransport(ROOT / "vault"))
    vault.load()
    return vault.reindex(generated=EPOCH)


def _stored(kind: str) -> str:
    return (ROOT / "expected" / f"{kind}.json").read_text(encoding="utf-8")


@pytest.mark.parametrize("kind", INDEX_KINDS)
def test_rebuild_reproduces_stored_index_byte_for_byte(
    kind: str, rebuilt: dict[str, dict]
) -> None:
    """§13: two implementations given the same content emit identical bytes."""
    want_text = _stored(kind)

    # §13.2: `generated` and the `etag` field of §10.1 are excluded from
    # comparison, since both legitimately differ — `generated` between two
    # runs, `etag` between two stores. Everything else must match exactly:
    # key order, indentation, escaping, element order.
    want = canonical_json(comparable(json.loads(want_text)))
    got = canonical_json(comparable(rebuilt[kind]))

    if got != want:
        # Report the first differing line rather than dumping two whole files.
        got_lines, want_lines = got.split("\n"), want.split("\n")
        at = next(
            (
                i
                for i in range(max(len(got_lines), len(want_lines)))
                if got_lines[i : i + 1] != want_lines[i : i + 1]
            ),
            0,
        )
        pytest.fail(
            f"index/{kind}.json differs at line {at + 1}\n"
            f"  expected: {want_lines[at] if at < len(want_lines) else '<end of file>'}\n"
            f"  actual:   {got_lines[at] if at < len(got_lines) else '<end of file>'}"
        )


@pytest.mark.parametrize("kind", INDEX_KINDS)
def test_whole_file_matches_including_etag(kind: str, rebuilt: dict[str, dict]) -> None:
    """Beyond §13.2: this transport's etags match the reference's too.

    §13.2 excludes ``etag`` from comparison because S3 implementations
    disagree about it, so a failure here is not a conformance failure. It is
    worth asserting anyway: both implementations compute a filesystem etag as
    the quoted MD5 of the bytes, so the *whole* file matching is a stronger
    check that nothing drifted, and `generated` stays the only excluded field.
    """
    want = _stored(kind)
    got = canonical_json(rebuilt[kind])
    assert got == want, f"index/{kind}.json differs once etag is included"


def test_every_index_cites_the_same_source_digest(rebuilt: dict[str, dict]) -> None:
    """§10: an index is trusted by digest, in one `get`, never by timestamp."""
    root = rebuilt["digest"]["root"]
    for kind in INDEX_KINDS:
        assert rebuilt[kind]["source_digest"] == root, f"{kind} cites a different digest"
        assert rebuilt[kind]["basalt"] == 1
        assert rebuilt[kind]["vault"] == "01JBQ7X8Z4N3VYK9M2T5HRWC6P"


def test_content_hash_is_present_and_authoritative(rebuilt: dict[str, dict]) -> None:
    """§10.1 — etags are useless across stores, so the hash is authoritative."""
    for entry in rebuilt["nodes"]["entries"]:
        assert str(entry["content_hash"]).startswith("sha256:"), entry["path"]


def test_backlinks_are_recomputable_from_links_alone(rebuilt: dict[str, dict]) -> None:
    """§10.3 — backlinks are derived wholly from the edge list."""
    recomputed: dict[str, list[str]] = {}
    for edge in rebuilt["links"]["entries"]:
        if edge["to"]:
            recomputed.setdefault(edge["to"], []).append(edge["from"])
    recomputed = {
        target: sorted(set(sources), key=lambda s: s.encode("utf-8"))
        for target, sources in recomputed.items()
    }
    assert recomputed == rebuilt["backlinks"]["entries"]


def test_gated_vault_leaks_no_text_into_search(rebuilt: dict[str, dict]) -> None:
    """§8.8 — the leak rule is normative, not advisory.

    No node in this vault grants ``publish`` to ``anonymous``, so none of its
    text may appear in ``search.json``. §8.1 is what makes this bite: the
    folder ACL grants ``read`` to ``everyone``, but a node reachable by
    ``anonymous`` needs ``publish`` as well.
    """
    assert rebuilt["search"]["terms"] == {}


def test_digest_is_independent_of_traversal_order() -> None:
    """§10.6 — sorting the leaf hashes, not the paths, is what buys this."""
    from basalt.indexer import compute_digest

    entries = [
        ("Notes/A.md", "sha256:" + "11" * 32),
        ("Notes/B.md", "sha256:" + "22" * 32),
        ("Assets/c.png", "sha256:" + "33" * 32),
    ]
    assert compute_digest(entries).root == compute_digest(entries[::-1]).root


def test_empty_content_tree_root() -> None:
    """§10.6 step 4 — the empty content tree has root sha256("")."""
    import hashlib

    from basalt.indexer import compute_digest

    assert compute_digest([]).root == "sha256:" + hashlib.sha256(b"").hexdigest()
